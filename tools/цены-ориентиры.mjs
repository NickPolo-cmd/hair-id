// Разбирает «318 / 518 / 738 мл», «500 / 1000 мл», «30 мл × 2», «480 г».
function объёмы(строка) {
  const т = String(строка || '');
  const множитель = (т.match(/[×x]\s*(\d+)/) || [])[1];
  const числа = [...т.matchAll(/(\d+)\s*(?:мл|г|ml)?/g)]
    .map((м) => Number(м[1]))
    .filter((н) => н >= 10);
  // \b не работает с кириллицей, поэтому границы слова задаём руками —
  // иначе «480 г» распознаётся как миллилитры.
  const единица = /(?:^|[^А-Яа-яЁёA-Za-z])г(?:[^А-Яа-яЁёA-Za-z]|$)/.test(т) ? 'г' : 'мл';
  if (множитель && числа.length) {
    // «30 мл × 2» — это один товар объёмом 60
    return [{ подпись: т.trim(), объём: числа[0] * Number(множитель) }];
  }
  const свои = числа.filter((н, i) => числа.indexOf(н) === i);
  if (!свои.length) return [{ подпись: т.trim() || '—', объём: 100 }];
  return свои.map((н) => ({ подпись: н + ' ' + единица, объём: н }));
}

const округлить = (ц) => Math.round(ц / 50) * 50;

const строки = [];
const отчёт = [];

for (const т of ТОВАРЫ) {
  const список = объёмы(т.volume);
  const свои = ЦЕНА_ВЛАДЕЛЬЦА[т.id];
  const кат = КАТЕГОРИЯ[т.id];

  if (!свои && !кат) {
    отчёт.push({ id: т.id, статус: 'НЕТ КАТЕГОРИИ', цены: [] });
    строки.push('# ' + т.id + ' — категория не задана, впишите цену руками');
    continue;
  }

  const опора = свои
    ? { объём: список[0].объём, цена: свои, где: 'цена владельца' }
    : РЫНОК[кат];

  const цены = список.map((о) =>
    округлить(опора.цена * Math.pow(о.объём / опора.объём, СТЕПЕНЬ_ОБЪЁМА) * (свои ? 1 : НАЦЕНКА))
  );

  строки.push(
    т.id + ' = ' + цены.join(' / ') +
    '   # ' + т.title + ' (' + т.volume + ')'
  );
  отчёт.push({
    id: т.id, имя: т.title, объёмы: список.map((о) => о.подпись),
    цены, основа: свои ? 'цена владельца' : кат, источник: опора.где,
  });
}


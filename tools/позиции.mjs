function польза(текст) {
  const строки = текст.split('\n').map(s => s.trim()).filter(Boolean);
  return строки.filter(s => /^[—-]\s/.test(s)).map(s => s.replace(/^[—-]\s*/, '')).slice(0, 8);
}
function состав(текст) {
  const м = текст.match(/(?:Состав|СОСТАВ\/INGREDIENTS)\s*:?\s*([\s\S]+)$/i);
  return м ? м[1].replace(/\s+/g, ' ').trim() : '';
}
function описание(текст) {
  const без = текст.split(/(?:Состав|СОСТАВ\/INGREDIENTS)\s*:/i)[0];
  const строки = без.split('\n').map(s => s.trim()).filter(Boolean)
    .filter(s => !/^[—-]\s/.test(s) && !/^Объ[её]м/i.test(s) && !/^Новинка/i.test(s));
  return строки.slice(1).join(' ').replace(/\s+/g, ' ').trim();
}

const позиции = [];
const служебные = [];
for (const с of сырьё) {
  const р = РАЗМЕТКА[с.id];
  if (!р) { служебные.push({ id: с.id, причина: 'нет в разметке' }); continue; }
  if (р.служебное) { служебные.push({ id: с.id, причина: р.служебное, текст: (с.исходныйТекст || '').trim() }); continue; }
  const т = с.исходныйТекст || '';
  позиции.push({
    id: с.id,
    бренд: р.бренд,
    категория: р.категория,
    название: р.назв,
    объём: р.объём,
    розница: р.розница || null,
    польза: польза(т),
    описание: описание(т),
    состав: состав(т),
    фотоИсходное: (с.фото || [])[0] || null,
    страна: (БРЕНДЫ[р.бренд] || {}).страна || '',
  });
}


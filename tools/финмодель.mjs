const среднее = (поле) => УСЛУГИ.reduce((s, у) => s + у[поле] * (СПРОС[у.код] || 0), 0);

const среднийЧек = среднее('цена');
const среднийЧас = среднее('часы');
const средняяСебестоимость = среднее('состав');

const ёмкостьЧасов = МОЩНОСТЬ.днейВМесяц * МОЩНОСТЬ.часовВДень * МОЩНОСТЬ.полезнаяДоля;
const ёмкостьВизитов = Math.floor(ёмкостьЧасов / среднийЧас);

function сценарий(имя) {
  const в = ВОРОНКА[имя];
  const б = БАЗА_КЛИЕНТОК[имя];

  const обращенийРеклама = Math.round(в.просмотры * в.вКонтакт);
  const обращенийБаза = Math.round(б.написано * б.откликнулись);
  const записейРеклама = Math.round(обращенийРеклама * в.вЗапись);
  const записейБаза = Math.round(обращенийБаза * б.записались);

  const пришлоНовых = Math.round((записейРеклама + записейБаза) * в.дошли);
  const повторных = Math.round(пришлоНовых * в.повторных);
  const визитовСпрос = пришлоНовых + повторных;

  // Потолок мастера. Если спрос выше — лишнее не превращается в деньги.
  const визитов = Math.min(визитовСпрос, ёмкостьВизитов);
  const очередь = Math.max(0, визитовСпрос - ёмкостьВизитов);

  const выручкаУслуги = визитов * среднийЧек;
  const себестоимостьСоставов = визитов * (средняяСебестоимость + 100); // +100 — одноразовое на визит

  const купилиТовар = Math.round(визитов * ТОВАР.доляКупивших[имя]);
  const выручкаТовар = купилиТовар * ТОВАР.среднийЧекТовара;
  const себестоимостьТовара = выручкаТовар * ТОВАР.себестоимостьДоля;

  const выручка = выручкаУслуги + выручкаТовар;
  const постоянные = Object.values(ПОСТОЯННЫЕ).reduce((a, b) => a + b, 0) + РЕКЛАМА[имя];
  // Налог: услуги по НПД, товар — по УСН, потому что НПД перепродажу не допускает.
  const налог = выручкаУслуги * НАЛОГ_НПД + выручкаТовар * НАЛОГ_УСН;

  const переменные = себестоимостьСоставов + себестоимостьТовара;
  const прибыль = выручка - переменные - постоянные - налог;

  const маржинальнаяПрибыль = выручка - переменные;
  const маржинальностьВизита = среднийЧек - средняяСебестоимость - 100;
  const точкаБезубыточности = Math.ceil(постоянные / маржинальностьВизита);
  // Значимая точка: сколько визитов закрывают личный минимум мастера.
  // Налог считаем по ставке услуг — товар в этой оценке не участвует.
  const визитовНаЛичныйМинимум = Math.ceil(
    (постоянные + ЛИЧНЫЙ_МИНИМУМ) / (маржинальностьВизита - среднийЧек * НАЛОГ_НПД)
  );
  const доходВЧас = Math.round(прибыль / Math.max(1, визитов * среднийЧас));

  return {
    имя,
    просмотры: в.просмотры,
    обращений: обращенийРеклама + обращенийБаза,
    обращенийРеклама, обращенийБаза,
    записей: записейРеклама + записейБаза,
    пришлоНовых, повторных,
    визитовСпрос, визитов, очередь,
    загрузка: +(визитов / ёмкостьВизитов).toFixed(3),
    часовЗанято: +(визитов * среднийЧас).toFixed(1),
    купилиТовар,
    выручкаУслуги: Math.round(выручкаУслуги),
    выручкаТовар: Math.round(выручкаТовар),
    выручка: Math.round(выручка),
    переменные: Math.round(переменные),
    постоянные: Math.round(постоянные),
    налог: Math.round(налог),
    маржинальнаяПрибыль: Math.round(маржинальнаяПрибыль),
    прибыль: Math.round(прибыль),
    среднийЧекВизита: Math.round(выручка / Math.max(1, визитов)),
    стоимостьОбращения: РЕКЛАМА[имя] ? Math.round(РЕКЛАМА[имя] / Math.max(1, обращенийРеклама)) : 0,
    точкаБезубыточности,
    визитовНаЛичныйМинимум,
    личныйМинимумЗакрыт: прибыль >= ЛИЧНЫЙ_МИНИМУМ,
    доходВЧас,
  };
}

// Год вперёд: сезонность из research/05 — дачный сезон апрель–сентябрь даёт
// кратный рост аудитории, зима держится на постоянных жителях.
// СЕЗОННОСТЬ — в бизнес/вводные.json
// Накопление базы: каждый месяц часть клиенток возвращается, поэтому спрос
// растёт даже при том же рекламном потоке. [оценка] 6% в месяц, консервативно.
// РОСТ_БАЗЫ — в бизнес/вводные.json

function год(имяСценария) {
  const с = сценарий(имяСценария);
  const месяцы = [];
  let накопление = 1;
  let итогВыручка = 0, итогПрибыль = 0;
  for (const [м, к] of Object.entries(СЕЗОННОСТЬ)) {
    const визитовСпрос = Math.round(с.визитовСпрос * к * накопление);
    const визитов = Math.min(визитовСпрос, ёмкостьВизитов);
    const выручкаУслуги = визитов * среднийЧек;
    const купили = Math.round(визитов * ТОВАР.доляКупивших[имяСценария]);
    const выручкаТовар = купили * ТОВАР.среднийЧекТовара;
    const выручка = выручкаУслуги + выручкаТовар;
    const переменные = визитов * (средняяСебестоимость + 100) + выручкаТовар * ТОВАР.себестоимостьДоля;
    const постоянные = Object.values(ПОСТОЯННЫЕ).reduce((a, b) => a + b, 0) + РЕКЛАМА[имяСценария];
    const налог = выручкаУслуги * НАЛОГ_НПД + выручкаТовар * НАЛОГ_УСН;
    const прибыль = выручка - переменные - постоянные - налог;
    итогВыручка += выручка; итогПрибыль += прибыль;
    месяцы.push({
      месяц: м, визитовСпрос, визитов,
      упёрлисьВПотолок: визитовСпрос > ёмкостьВизитов,
      выручка: Math.round(выручка), прибыль: Math.round(прибыль),
      загрузка: +(визитов / ёмкостьВизитов).toFixed(2),
    });
    накопление *= 1 + РОСТ_БАЗЫ;
  }
  return { сценарий: имяСценария, месяцы, итогВыручка: Math.round(итогВыручка), итогПрибыль: Math.round(итогПрибыль) };
}


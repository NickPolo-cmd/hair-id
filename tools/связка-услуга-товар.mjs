const путьТоваров = path.join(КОРЕНЬ, 'site-shop', 'js', 'products.data.js');
const исходник = fs.readFileSync(путьТоваров, 'utf8');
const ТОВАРЫ = JSON.parse(исходник.slice(исходник.indexOf('[')).replace(/;\s*$/, ''));
const поId = Object.fromEntries(ТОВАРЫ.map((т) => [т.id, т]));

// Адреса в исходниках — netlify; сборка docs/ переписывает их сама вместе
// со всеми остальными ссылками, поэтому здесь именно исходные адреса.
const АДРЕС_МАГАЗИНА = 'https://hairid-shop.netlify.app';
const АДРЕС_СТУДИИ = 'https://hairid.netlify.app';

const экран = (т) => т.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const экранJS = (т) => JSON.stringify(т);
const вРегексп = (т) => т.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// Вырезает прошлый прогон между метками. Без этого блоки копятся при каждом
// запуске, и страница за пять прогонов обрастает пятью одинаковыми списками.
function вырезать(текст, начало, конец) {
  return текст.replace(
    new RegExp('[ \\t]*' + вРегексп(начало) + '[\\s\\S]*?' + вРегексп(конец) + '\\n?', 'g'),
    ''
  );
}

function товар(запись, т) {
  const найден = поId[т.id];
  if (!найден) {
    throw new Error(`Товара ${т.id} нет в каталоге (услуга «${запись.услуга}»). ` +
      `Каталог пересобирался? Поправьте связку в tools/связка-услуга-товар.mjs.`);
  }
  return найден;
}


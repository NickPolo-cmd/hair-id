const путьТоваров = path.join(КОРЕНЬ, 'site-shop', 'js', 'products.data.js');
const исходник = fs.readFileSync(путьТоваров, 'utf8');
const ТОВАРЫ = JSON.parse(исходник.slice(исходник.indexOf('[')).replace(/;\s*$/, ''));
const поId = Object.fromEntries(ТОВАРЫ.map((т) => [т.id, т]));

// Адрес магазина в исходниках — netlify; сборка docs/ переписывает его сама
// вместе со всеми остальными ссылками, поэтому здесь именно исходный адрес.
const АДРЕС_МАГАЗИНА = 'https://hairid-shop.netlify.app';

const экран = (т) => т.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const МЕТКА_НАЧАЛО = '<!-- СВЯЗКА-УХОД: собрано tools/связка-услуга-товар.mjs, руками не править -->';
const МЕТКА_КОНЕЦ = '<!-- /СВЯЗКА-УХОД -->';

function блок(запись) {
  const позиции = запись.товары.map((т) => {
    const товар = поId[т.id];
    if (!товар) {
      throw new Error(`Товара ${т.id} нет в каталоге (услуга «${запись.услуга}»). ` +
        `Каталог пересобирался? Поправьте связку в tools/связка-услуга-товар.mjs.`);
    }
    return '        <li><a href="' + АДРЕС_МАГАЗИНА + '/katalog.html#' + т.id + '">' +
      экран(товар.title) + '</a> — ' + экран(т.почему) + '</li>';
  }).join('\n');

  return [
    '      ' + МЕТКА_НАЧАЛО,
    '      <details class="usluga__uhod">',
    '        <summary>Что взять домой после этой процедуры</summary>',
    '        <p>' + экран(запись.зачем) + '</p>',
    '        <ul>',
    позиции,
    '        </ul>',
    '        <p class="usluga__uhod-note">Это не обязательная покупка. Если то, что у вас есть, ' +
      'подходит — так и скажу на приёме.</p>',
    '      </details>',
    '      ' + МЕТКА_КОНЕЦ,
  ].join('\n');
}


const путьУслуг = path.join(КОРЕНЬ, 'site', 'uslugi.html');
let страница = fs.readFileSync(путьУслуг, 'utf8');

// Убираем прошлый прогон целиком, чтобы блоки не накапливались
страница = страница.replace(
  new RegExp('\\s*' + МЕТКА_НАЧАЛО.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') +
    '[\\s\\S]*?' + МЕТКА_КОНЕЦ.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g'),
  '');

let вставлено = 0;
const ненайденные = [];

for (const запись of СВЯЗКА) {
  // Ищем карточку по заголовку и вставляем блок перед ссылкой «Записаться»
  const заголовок = '<h3>' + запись.услуга + '</h3>';
  const начало = страница.indexOf(заголовок);
  if (начало === -1) { ненайденные.push(запись.услуга); continue; }

  const конецКарточки = страница.indexOf('</article>', начало);
  const ссылка = страница.lastIndexOf('<a class="card-go"', конецКарточки);
  if (конецКарточки === -1 || ссылка === -1 || ссылка < начало) {
    ненайденные.push(запись.услуга + ' (не найден конец карточки)');
    continue;
  }

  const отступ = страница.slice(страница.lastIndexOf('\n', ссылка) + 1, ссылка);
  страница = страница.slice(0, ссылка) + блок(запись).trimStart() + '\n' + отступ + страница.slice(ссылка);
  вставлено++;
}

fs.writeFileSync(путьУслуг, страница);

console.log('Блоков «что взять домой» вставлено: ' + вставлено + ' из ' + СВЯЗКА.length);
if (ненайденные.length) {
  console.log('НЕ НАЙДЕНЫ карточки услуг: ' + ненайденные.join(', '));
  console.log('Проверьте, совпадает ли заголовок <h3> в site/uslugi.html с полем «услуга».');
  process.exit(1);
}

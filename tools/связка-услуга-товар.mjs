// 1. Страница услуг: блок «что взять домой»

const М1_НАЧАЛО = '<!-- СВЯЗКА-УХОД: собрано tools/связка-услуга-товар.mjs, руками не править -->';
const М1_КОНЕЦ = '<!-- /СВЯЗКА-УХОД -->';

function блокУхода(запись) {
  const позиции = запись.товары.map((т) => {
    return '        <li><a href="' + АДРЕС_МАГАЗИНА + '/katalog.html#' + т.id + '">' +
      экран(товар(запись, т).title) + '</a> — ' + экран(т.почему) + '</li>';
  }).join('\n');

  return [
    '      ' + М1_НАЧАЛО,
    '      <details class="usluga__uhod">',
    '        <summary>Что взять домой после этой процедуры</summary>',
    '        <p>' + экран(запись.зачем) + '</p>',
    '        <ul>',
    позиции,
    '        </ul>',
    '        <p class="usluga__uhod-note">Это не обязательная покупка. Если то, что у вас есть, ' +
      'подходит — так и скажу на приёме.</p>',
    '      </details>',
    '      ' + М1_КОНЕЦ,
  ].join('\n');
}

const путьУслуг = path.join(КОРЕНЬ, 'site', 'uslugi.html');
let страницаУслуг = fs.readFileSync(путьУслуг, 'utf8');
страницаУслуг = вырезать(страницаУслуг, М1_НАЧАЛО, М1_КОНЕЦ);

let вставлено = 0;
const ненайденные = [];
// Якоря карточек услуг снимаем прямо с разметки, а не пишем руками:
// иначе однажды id в html переименуют, а ссылка из магазина будет вести
// в никуда — и никто этого не заметит, потому что якорь «просто не сработает».
const якоря = {};

for (const запись of СВЯЗКА) {
  const заголовок = '<h3>' + запись.услуга + '</h3>';
  const начало = страницаУслуг.indexOf(заголовок);
  if (начало === -1) { ненайденные.push(запись.услуга); continue; }

  const открытие = страницаУслуг.lastIndexOf('<article', начало);
  const совпадение = /id="([^"]+)"/.exec(страницаУслуг.slice(открытие, начало));
  if (!совпадение) { ненайденные.push(запись.услуга + ' (у карточки нет id)'); continue; }
  якоря[запись.услуга] = совпадение[1];

  const конецКарточки = страницаУслуг.indexOf('</article>', начало);
  const ссылка = страницаУслуг.lastIndexOf('<a class="card-go"', конецКарточки);
  if (конецКарточки === -1 || ссылка === -1 || ссылка < начало) {
    ненайденные.push(запись.услуга + ' (не найден конец карточки)');
    continue;
  }

  const отступ = страницаУслуг.slice(страницаУслуг.lastIndexOf('\n', ссылка) + 1, ссылка);
  страницаУслуг = страницаУслуг.slice(0, ссылка) + блокУхода(запись).trimStart() +
    '\n' + отступ + страницаУслуг.slice(ссылка);
  вставлено++;
}

if (ненайденные.length) {
  console.log('НЕ НАЙДЕНЫ карточки услуг: ' + ненайденные.join(', '));
  console.log('Проверьте, совпадает ли заголовок <h3> в site/uslugi.html с полем «услуга».');
  process.exit(1);
}

fs.writeFileSync(путьУслуг, страницаУслуг);


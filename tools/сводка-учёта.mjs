// Сводка по таблице учёта: что было запланировано и что вышло на самом деле.
//
// Зачем: `marketing/УЧЁТ.csv` заполняется руками раз в неделю, а план на месяц
// живёт в `бизнес/финмодель.json`. Пока их никто не сводит вместе, таблица —
// просто столбик цифр: непонятно, много это или мало. Этот скрипт кладёт факт
// рядом с планом и говорит, где именно рвётся цепочка.
//
// Запуск:  node tools/сводка-учёта.mjs
//          node tools/сводка-учёта.mjs --сценарий цель
//
// Ничего не выдумывает: пустые недели пропускаются, и если заполнено ноль
// недель — так и пишет, а не рисует красивый ноль.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const КОРЕНЬ = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const сценарийИмя = (() => {
  const i = process.argv.indexOf('--сценарий');
  return i !== -1 && process.argv[i + 1] ? process.argv[i + 1] : 'база';
})();

// ---------------------------------------------------------------------------
// Читаем план
// ---------------------------------------------------------------------------

const путьМодели = path.join(КОРЕНЬ, 'бизнес', 'финмодель.json');
if (!fs.existsSync(путьМодели)) {
  console.log('Нет файла бизнес/финмодель.json. Сначала: node tools/финмодель.mjs');
  process.exit(1);
}
const модель = JSON.parse(fs.readFileSync(путьМодели, 'utf8'));
const план = модель.сценарииМесяца.find((с) => с.имя === сценарийИмя);
if (!план) {
  console.log('Нет сценария «' + сценарийИмя + '». Есть: ' +
    модель.сценарииМесяца.map((с) => с.имя).join(', '));
  process.exit(1);
}

// ---------------------------------------------------------------------------
// Читаем факт
// ---------------------------------------------------------------------------

const путьУчёта = path.join(КОРЕНЬ, 'marketing', 'УЧЁТ.csv');
const сырое = fs.readFileSync(путьУчёта, 'utf8').replace(/^﻿/, '');
const строки = сырое.trim().split(/\r?\n/).map((с) => с.split(';'));
const шапка = строки[0];

// Номера столбцов ищем по названию, а не по порядку: столбец могли подвинуть,
// и молчаливый сдвиг на единицу дал бы правдоподобные, но неверные цифры.
function столбец(кусок) {
  const i = шапка.findIndex((з) => з.toLowerCase().includes(кусок.toLowerCase()));
  if (i === -1) throw new Error('В шапке УЧЁТ.csv нет столбца со словом «' + кусок + '»');
  return i;
}

const К = {
  неделя: столбец('Неделя'),
  сДата: столбец('Дата с'),
  просмотры: столбец('Просмотры'),
  обращения: столбец('Обращений'),
  диагностика: столбец('Дошли до диагностики'),
  записались: столбец('Записались'),
  пришли: столбец('Пришли'),
  выручкаУслуги: столбец('Выручка услуги'),
  выручкаТовар: столбец('Выручка товар'),
  повторных: столбец('Повторных'),
  отзывов: столбец('Новых отзывов'),
  реклама: столбец('Потрачено на рекламу'),
};

const число = (з) => {
  if (з === undefined) return null;
  const т = String(з).trim();
  if (!т || т.startsWith('=')) return null;       // формулы считает Excel, не мы
  const n = Number(т.replace(/\s/g, '').replace(',', '.'));
  return Number.isFinite(n) ? n : null;
};

const заполненные = строки.slice(1).filter((р) => {
  // Неделя считается заполненной, если есть хоть одно из ключевых чисел
  return [К.просмотры, К.обращения, К.записались, К.пришли, К.выручкаУслуги]
    .some((к) => число(р[к]) !== null);
});

console.log('\n═══ СВОДКА УЧЁТА HAIR ID ═══');
console.log('Сценарий плана: ' + план.имя);

if (!заполненные.length) {
  console.log('\nТаблица marketing/УЧЁТ.csv пока пуста — заполненных недель нет.');
  console.log('Сравнивать не с чем. Это не поломка: до первой рабочей недели так и должно быть.');
  console.log('\nЧто должно появиться за месяц по плану «' + план.имя + '»:');
  console.log('  обращений ' + план.обращений + ', записей ' + план.записей +
    ', визитов ' + план.визитов);
  console.log('  выручка ' + план.выручка.toLocaleString('ru-RU') + ' ₽ ' +
    '(услуги ' + план.выручкаУслуги.toLocaleString('ru-RU') + ' + товар ' +
    план.выручкаТовар.toLocaleString('ru-RU') + ')');
  console.log('\nЗаполняется раз в неделю, в один и тот же день. Инструкция:');
  console.log('  marketing/УЧЁТ-инструкция.md');
  process.exit(0);
}

// ---------------------------------------------------------------------------
// Складываем факт
// ---------------------------------------------------------------------------

const сумма = (к) => заполненные.reduce((с, р) => с + (число(р[к]) || 0), 0);

const факт = {
  недель: заполненные.length,
  просмотры: сумма(К.просмотры),
  обращения: сумма(К.обращения),
  диагностика: сумма(К.диагностика),
  записались: сумма(К.записались),
  пришли: сумма(К.пришли),
  выручкаУслуги: сумма(К.выручкаУслуги),
  выручкаТовар: сумма(К.выручкаТовар),
  повторных: сумма(К.повторных),
  отзывов: сумма(К.отзывов),
  реклама: сумма(К.реклама),
};
факт.выручка = факт.выручкаУслуги + факт.выручкаТовар;

// План на месяц приводим к прожитой части месяца, иначе сравнение бессмысленно:
// две недели факта против месяца плана всегда выглядят провалом.
const доля = Math.min(1, факт.недель / 4.35);
const кДате = (n) => Math.round(n * доля);

const руб = (n) => Math.round(n).toLocaleString('ru-RU') + ' ₽';
const строка = (имя, ф, п, ед) => {
  const план = кДате(п);
  const знак = план === 0 ? '·' : ф >= план ? '✓' : ф >= план * 0.8 ? '≈' : '✗';
  const проц = план === 0 ? '' : ' (' + Math.round((ф / план) * 100) + '%)';
  const показ = ед === '₽' ? [руб(ф), руб(план)] : [String(ф), String(план)];
  console.log('  ' + знак + ' ' + имя.padEnd(26) + показ[0].padStart(12) +
    '   план ' + показ[1].padStart(12) + проц);
};

console.log('Заполнено недель: ' + факт.недель + ' — это ' + Math.round(доля * 100) + '% месяца.');
console.log('План ниже пересчитан на эту же долю месяца, иначе сравнение врёт.\n');

console.log('ВОРОНКА');
строка('Просмотры объявлений', факт.просмотры, план.просмотры);
строка('Обращений', факт.обращения, план.обращений);
строка('Записались', факт.записались, план.записей);
строка('Пришли', факт.пришли, план.визитов);
строка('Повторных визитов', факт.повторных, план.повторных);

console.log('\nДЕНЬГИ');
строка('Выручка услуг', факт.выручкаУслуги, план.выручкаУслуги, '₽');
строка('Выручка товара', факт.выручкаТовар, план.выручкаТовар, '₽');
строка('Выручка всего', факт.выручка, план.выручка, '₽');

// ---------------------------------------------------------------------------
// Где рвётся цепочка
// ---------------------------------------------------------------------------

console.log('\nГДЕ РВЁТСЯ ЦЕПОЧКА');

const переходы = [
  { имя: 'просмотр → обращение', факт: факт.просмотры ? факт.обращения / факт.просмотры : null,
    план: план.просмотры ? план.обращенийРеклама / план.просмотры : null },
  { имя: 'обращение → запись', факт: факт.обращения ? факт.записались / факт.обращения : null,
    план: план.обращений ? план.записей / план.обращений : null },
  { имя: 'запись → пришла', факт: факт.записались ? факт.пришли / факт.записались : null,
    план: план.записей ? план.пришлоНовых / план.записей : null },
];

let слабое = null;
for (const п of переходы) {
  if (п.факт === null || п.план === null) {
    console.log('  ' + п.имя.padEnd(26) + 'нет данных');
    continue;
  }
  const отставание = п.план ? п.факт / п.план : 1;
  if (слабое === null || отставание < слабое.отставание) слабое = { ...п, отставание };
  console.log('  ' + п.имя.padEnd(26) +
    (п.факт * 100).toFixed(1).padStart(6) + '%   план ' + (п.план * 100).toFixed(1) + '%');
}

if (слабое && слабое.отставание < 0.85) {
  console.log('\n  Самое слабое звено: ' + слабое.имя +
    ' — ' + Math.round((1 - слабое.отставание) * 100) + '% ниже плана.');
  const советы = {
    'просмотр → обращение': 'Дело в самих объявлениях: заголовок, первое фото, цена. ' +
      'Воронку ниже чинить бессмысленно, пока не идут обращения.',
    'обращение → запись': 'Дело в переписке. Смотрите шпаргалку site/cheatsheet.html: ' +
      'цену первой репликой не называть, сначала разбор проблемы.',
    'запись → пришла': 'Люди записываются и не доезжают. Нужны подтверждение накануне ' +
      'и понятная дорога — это дыра в середине воронки, а не в рекламе.',
  };
  console.log('  ' + (советы[слабое.имя] || ''));
}

// ---------------------------------------------------------------------------
// Стоимость обращения и отзывы
// ---------------------------------------------------------------------------

console.log('\nПРОЧЕЕ');
if (факт.реклама && факт.обращения) {
  console.log('  Стоимость обращения: ' + руб(факт.реклама / факт.обращения) +
    ' (потрачено ' + руб(факт.реклама) + ' на ' + факт.обращения + ' обращений)');
} else if (!факт.реклама) {
  console.log('  На рекламу не потрачено ничего — стоимость обращения считать не из чего.');
}
console.log('  Новых отзывов: ' + факт.отзывов + ' из 10 нужных за месяц');
if (факт.пришли) {
  console.log('  Средний чек визита: ' + руб(факт.выручка / факт.пришли) +
    '   план ' + руб(план.среднийЧекВизита));
}

// ---------------------------------------------------------------------------
// Что из предпосылок модели уже можно заменить фактом
// ---------------------------------------------------------------------------

console.log('\nЧТО УЖЕ МОЖНО ПЕРЕСТАТЬ УГАДЫВАТЬ');
const замеры = [];
if (факт.просмотры) замеры.push('просмотры объявлений: ' + Math.round(факт.просмотры / доля) + ' в месяц');
if (факт.просмотры && факт.обращения)
  замеры.push('доля перешедших в обращение: ' + (факт.обращения / факт.просмотры * 100).toFixed(1) + '%');
if (факт.обращения && факт.записались)
  замеры.push('доля записавшихся: ' + (факт.записались / факт.обращения * 100).toFixed(0) + '%');
if (факт.записались && факт.пришли)
  замеры.push('доходимость: ' + (факт.пришли / факт.записались * 100).toFixed(0) + '%');
if (факт.пришли && факт.выручкаУслуги)
  замеры.push('средний чек услуги: ' + Math.round(факт.выручкаУслуги / факт.пришли) + ' ₽');

if (замеры.length) {
  замеры.forEach((з) => console.log('  · ' + з));
  console.log('\n  Впишите эти числа в tools/финмодель.mjs вместо пометок [оценка]');
  console.log('  и пересчитайте: node tools/финмодель.mjs');
} else {
  console.log('  Пока нечего: не хватает заполненных столбцов.');
}
console.log('');

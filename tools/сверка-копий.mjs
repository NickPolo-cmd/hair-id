// Сверка парных файлов студии и магазина.
//
// Зачем. Студия и магазин — два отдельных сайта с общим набором файлов:
// движок движения, фактуры, счётчик, стили. Файлы лежат в двух копиях.
// Правку делают в одной, вторую забывают — и копия молча отстаёт.
// Так и случилось: параллакс в студии переписали на запомненные места
// (в двадцать раз меньше обращений к раскладке), а в магазине он полгода
// оставался медленным. Нашлось это случайно, а не проверкой.
//
// Что делает. Сравнивает парные файлы, показывает, где они разошлись,
// и печатает первые строки расхождения. Ничего не правит: решение,
// какая версия верная, принимает человек.
//
// Запуск: node tools/сверка-копий.mjs
// Код возврата 1, если есть расхождения сверх разрешённых.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const КОРЕНЬ = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

// Пары «файл студии → файл магазина». Берём только то, что задумано общим:
// страницы и данные у сайтов свои, их сверять нечего.
const ПАПКИ = ['css', 'js'];

// Файлы, которым положено различаться, и почему. Без этого списка сверка
// каждый раз ругалась бы на осмысленные различия, и её перестали бы читать.
const РАЗРЕШЕНО = {
  'css/pages.css': 'у сайтов разные страницы: услуги и работы против каталога и наборов',
  'css/shape.css': 'формы блоков у страниц услуг и карточек товара разные',
  'css/tokens.css': 'магазину не нужны токены форм записи, студии — токены корзины',
  'css/doc.css': 'у студии есть форма согласия на фото, у магазина её нет',
  'css/motion.css': 'в магазине нет бегущей строки, залипаний и перелёта логотипа',
  'js/motion.js': 'то же: магазинному движку эти три блока не нужны',
  'js/catalog.js': 'только у магазина',
  'js/booking.js': 'только у студии',
  'js/analytics.js': 'в инструкции к счётчику стоит адрес своего сайта: студии и магазина',
};

const расхождения = [];
const совпали = [];

for (const папка of ПАПКИ) {
  const путьС = path.join(КОРЕНЬ, 'site', папка);
  const путьМ = path.join(КОРЕНЬ, 'site-shop', папка);
  if (!fs.existsSync(путьС) || !fs.existsSync(путьМ)) continue;

  for (const имя of fs.readdirSync(путьС)) {
    const а = path.join(путьС, имя);
    const б = path.join(путьМ, имя);
    if (!fs.statSync(а).isFile() || !fs.existsSync(б)) continue;

    const ключ = папка + '/' + имя;
    const тА = fs.readFileSync(а, 'utf8');
    const тБ = fs.readFileSync(б, 'utf8');
    if (тА === тБ) { совпали.push(ключ); continue; }

    const строкиА = тА.split('\n');
    const строкиБ = тБ.split('\n');
    let перваяРазница = -1;
    for (let i = 0; i < Math.max(строкиА.length, строкиБ.length); i++) {
      if (строкиА[i] !== строкиБ[i]) { перваяРазница = i + 1; break; }
    }
    расхождения.push({
      ключ,
      разрешено: РАЗРЕШЕНО[ключ] || null,
      строкС: строкиА.length, строкМ: строкиБ.length,
      перваяРазница,
    });
  }
}

console.log('Совпадают байт в байт: ' + совпали.length +
            (совпали.length ? ' (' + совпали.join(', ') + ')' : ''));

const неожиданные = расхождения.filter((р) => !р.разрешено);

if (расхождения.length) {
  console.log('\nРазошлись:');
  for (const р of расхождения) {
    console.log('  ' + (р.разрешено ? 'так и задумано  ' : 'ВНИМАНИЕ        ') + р.ключ +
      '  строк ' + р.строкС + ' против ' + р.строкМ +
      ', первая разница в строке ' + р.перваяРазница);
    if (р.разрешено) console.log('      почему: ' + р.разрешено);
  }
}

if (неожиданные.length) {
  console.log('\nЭти пары должны быть одинаковыми, но разошлись — ' +
    'проверьте, не забыли ли перенести правку во вторую копию:');
  for (const р of неожиданные) console.log('  ' + р.ключ);
  process.exit(1);
}

console.log('\nНеожиданных расхождений нет.');
process.exit(0);

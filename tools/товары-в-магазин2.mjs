// Из поставщик/позиции.json -> site-shop/js/products.data.js
// Цены берутся из товары-цены.txt, если он заполнен. Ничего не придумывается.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const КОРЕНЬ = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const данные = JSON.parse(fs.readFileSync(path.join(КОРЕНЬ, 'поставщик/позиции.json'), 'utf8'));

// ── цены владельца ──────────────────────────────────────────────────────────
const файлЦен = path.join(КОРЕНЬ, 'товары-цены.txt');
const цены = {};
if (fs.existsSync(файлЦен)) {
  for (const строка of fs.readFileSync(файлЦен, 'utf8').split('\n')) {
    const м = строка.match(/^\s*(t\d{3})\s*=\s*(\d[\d\s]*)/);
    if (м) цены[м[1]] = parseInt(м[2].replace(/\s/g, ''), 10);
  }
}

// ── задача, ради которой средство берут ─────────────────────────────────────
const ПРИЗНАКИ = [
  ['scalp',   /жирн|сальн|перхот|кожи головы|очистк|ментол|чайного дерева|имбир|пилинг/i],
  ['damaged', /повреж|осветл|ломк|порист|реконструк|восстанавлив|кератин|протеин|секущ/i],
  ['dry',     /сух|увлажн|питат|питани|масло|ши\b|гиалурон|коллаген|тускл/i],
  ['frizz',   /пушист|разглаж|выпрямл|непослушн|кудряв|локон|шёлк|гладк/i],
  ['styling', /укладк|стайлинг|термозащит|объём|спрей|несмываем|крем для/i],
  ['after',   /после ботокса|после кератина|после процедур|стойкост цвет|окрашенн/i],
];

function задачи(п) {
  const текст = [п.название, п.описание, п.польза.join(' ')].join(' ');
  const найдено = ПРИЗНАКИ.filter(([, re]) => re.test(текст)).map(([к]) => к);
  return найдено.length ? найдено.slice(0, 3) : ['dry'];
}

// ── тексты карточки ─────────────────────────────────────────────────────────
function кому(п) {
  const п1 = п.польза[0];
  return п1 ? п1.replace(/^./, c => c.toUpperCase()).replace(/\.$/, '') : п.категория + ' ' + п.бренд;
}
function почему(п) {
  const хвост = п.польза.slice(1, 4).join('. ');
  const начало = п.описание ? п.описание.split('. ').slice(0, 2).join('. ') : '';
  const т = (начало + (хвост ? '. ' + хвост : '')).trim();
  return т ? (т.endsWith('.') ? т : т + '.') : 'Профессиональное средство линии ' + п.бренд + '.';
}
const КАК = {
  'Шампунь': 'Нанести на влажные волосы, вспенить, тщательно смыть. При необходимости повторить.',
  'Кондиционер': 'После шампуня отжать воду, нанести по длине, отступив от корней. Оставить на 1–2 минуты, смыть.',
  'Маска': 'На чистые влажные волосы по длине, отступив от корней. Выдержка 3–5 минут, затем смыть тёплой водой.',
  'Масло': 'Две-три капли на сухие или влажные концы, распределить руками. Не смывать.',
  'Сыворотка': 'Распылить на подсушенные полотенцем волосы перед укладкой. Не смывать.',
  'Стайлинг': 'Распылить у корней на влажные волосы, уложить феном.',
  'Несмываемый уход': 'Небольшое количество на влажные волосы по длине. Не смывать.',
};

const товары = данные.позиции.map(п => {
  const фото = 'assets/photo/tovary/' + п.id + '.webp';
  const естьФото = fs.existsSync(path.join(КОРЕНЬ, 'site-shop', фото));
  return {
    id: п.id,
    title: п.название.length > 62 ? п.название.slice(0, 59).trim() + '…' : п.название,
    subtitle: п.бренд + ', ' + п.категория.toLowerCase(),
    task: задачи(п),
    price: цены[п.id] || п.розница || null,
    volume: п.объём,
    photo: естьФото ? фото : 'assets/photo/care-bottle.jpg',
    forWhom: кому(п),
    notFor: '—',
    why: почему(п),
    how: КАК[п.категория] || 'По инструкции на упаковке.',
    бренд: п.бренд,
  };
});

const заголовок = `// Товары магазина Hair ID.
// Файл собирается командой: node tools/товары-в-магазин2.mjs
// Источник — карточки, присланные владельцем боту в Telegram.
// Цены берутся из товары-цены.txt; пока строка пустая, карточка
// показывает «цена по запросу» — придуманных цен здесь нет.
window.HAIRID_PRODUCTS = `;

fs.writeFileSync(
  path.join(КОРЕНЬ, 'site-shop/js/products.data.js'),
  заголовок + JSON.stringify(товары, null, 1) + ';\n'
);

// шаблон для цен, если его ещё нет
if (!fs.existsSync(файлЦен)) {
  let ш = '# Цены товаров Hair ID\n# Впишите розничную цену в рублях после знака "=" и сохраните файл.\n';
  ш += '# Потом выполните: node tools/товары-в-магазин2.mjs\n# Пустая строка = на сайте будет «цена по запросу».\n\n';
  let бренд = '';
  for (const п of данные.позиции) {
    if (п.бренд !== бренд) { бренд = п.бренд; ш += '\n## ' + бренд + '\n'; }
    ш += п.id + ' = ' + (п.розница || '') + '   # ' + п.название + ' (' + п.объём + ')\n';
  }
  fs.writeFileSync(файлЦен, ш);
  console.log('создан шаблон цен: товары-цены.txt');
}

const сЦеной = товары.filter(т => т.price).length;
const сФото = товары.filter(т => т.photo.includes('tovary/')).length;
console.log('товаров в магазине:', товары.length, '| с ценой:', сЦеной, '| со своим фото:', сФото);
const поЗадачам = {};
for (const т of товары) for (const з of т.task) поЗадачам[з] = (поЗадачам[з] || 0) + 1;
console.log('по задачам:', поЗадачам);

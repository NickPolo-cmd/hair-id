// Собирает из НОМЕНКЛАТУРА.md таблицу-приложение к запросу коммерческого предложения.
// Два файла: русский для Беларуси и английский для Китая. CSV с BOM и точкой с запятой —
// так его открывает русский Excel без плясок с кодировкой и колонками.
import fs from 'node:fs';

const текст = fs.readFileSync('/Users/nick/Desktop/Волосы/поставщик/НОМЕНКЛАТУРА.md', 'utf8');

const позиции = [];
let бренд = null;
for (const строка of текст.split('\n')) {
  const заголовок = строка.match(/^##\s+([A-ZА-Я][A-ZА-Я\s]+?)\s+—\s+\d+\s+позиц/);
  if (заголовок) { бренд = заголовок[1].trim(); continue; }
  if (!бренд || !строка.startsWith('|')) continue;
  const я = строка.split('|').map(s => s.trim());
  // | № | рус | EN | категория | объём | упаковка | ТН ВЭД | розница | закупочная |
  if (я.length < 10) continue;
  if (!/^\d+$/.test(я[1])) continue;
  позиции.push({ бренд, рус: я[2], en: я[3], категория: я[4], объём: я[5], упаковка: я[6], тнвэд: я[7] });
}

const экран = з => {
  const s = String(з == null ? '' : з);
  return /[;"\n]/.test(s) ? '"' + s.replace(/"/g, '""') + '"' : s;
};
const собрать = (шапка, строки) => '﻿' + [шапка, ...строки].map(р => р.map(экран).join(';')).join('\r\n') + '\r\n';

// ---- русский вариант (Беларусь, контрактное производство) ----
const рус = собрать(
  ['№', 'Бренд-образец', 'Наименование', 'Категория', 'Объём', 'Упаковка', 'Код ТН ВЭД',
   'Кол-во на пробу, шт', 'Кол-во на первый заказ, шт', 'Цена за ед., ₽ (заполняет поставщик)',
   'Срок изготовления (заполняет поставщик)', 'MOQ по позиции (заполняет поставщик)'],
  позиции.map((п, i) => [i + 1, п.бренд, п.рус, п.категория, п.объём, п.упаковка, п.тнвэд, '', '', '', '', '']),
);

// ---- английский вариант (Китай) ----
const en = собрать(
  ['No', 'Reference brand', 'Product name', 'Category', 'Volume', 'Packaging', 'HS code',
   'Sample qty, pcs', 'First order qty, pcs', 'Unit price, USD (supplier fills)',
   'Lead time (supplier fills)', 'MOQ per item (supplier fills)'],
  позиции.map((п, i) => [i + 1, п.бренд, п.en, п.категория, п.объём, п.упаковка, п.тнвэд, '', '', '', '', '']),
);

fs.writeFileSync('/Users/nick/Desktop/Волосы/поставщик/КП-таблица-РУС.csv', рус, 'utf8');
fs.writeFileSync('/Users/nick/Desktop/Волосы/поставщик/КП-таблица-ENG.csv', en, 'utf8');

const поБрендам = {};
позиции.forEach(п => { поБрендам[п.бренд] = (поБрендам[п.бренд] || 0) + 1; });
console.log('позиций:', позиции.length, поБрендам);
console.log('категории:', [...new Set(позиции.map(п => п.категория))].join(', '));

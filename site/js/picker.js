  function initPicker() {
    var cards = document.querySelectorAll('[data-picker]');
    var result = document.getElementById('picker-result');
    if (!cards.length || !result) return;

    // Ответ — это блок в несколько абзацев со ссылкой на запись, и человеку
    // нужно на него попасть. Делаем блок доступным для программного фокуса;
    // в обход по Tab он от этого не попадает — только -1.
    result.setAttribute('tabindex', '-1');

    cards.forEach(function (card) {
      card.setAttribute('aria-pressed', 'false');

      card.addEventListener('click', function () {
        var key = card.getAttribute('data-picker');
        var data = ANSWERS[key];
        if (!data) return;

        cards.forEach(function (other) {
          other.setAttribute('aria-pressed', other === card ? 'true' : 'false');
        });

        // Показываем блок ДО того, как в него пишем. Пока стоит hidden,
        // у элемента display: none, и в дереве доступности его нет совсем —
        // значит, нет и живой области, внутри которой могла бы произойти
        // мутация, и скринридеру нечего объявлять.
        result.hidden = false;

        result.innerHTML =
          '<h3>' + data.title + '</h3>' +
          '<p><strong>Что происходит.</strong> ' + data.why + '</p>' +
          '<p><strong>Что делаем.</strong> ' + data.what + '</p>' +
          '<ul class="picker__services">' +
            data.services.map(function (s) { return '<li>' + s + '</li>'; }).join('') +
          '</ul>' +
          '<p class="t-small t-muted">' + data.note + '</p>' +
          '<a href="#booking" class="btn btn-primary" style="margin-top:1.5rem">Записаться на диагностику</a>';

        // Пересчитываем высоту страницы: блок ответа изменил её.
        if (window.HairIDMotion) window.HairIDMotion.refresh();

        // Одной живой области мало: она появляется в дереве доступности
        // в тот же момент, что и текст в ней, и часть скринридеров такую пару
        // пропускает. Фокус на ответе читается всегда, и заодно человек уже
        // стоит там, откуда до кнопки «Записаться» один Tab.
        // preventScroll — чтобы браузер не прыгнул сам: прокруткой ниже
        // занимается движок анимаций.
        try { result.focus({ preventScroll: true }); } catch (e) { result.focus(); }

        // Показываем ответ, но не выдёргиваем страницу из-под пользователя.
        var rect = result.getBoundingClientRect();
        if (rect.bottom > window.innerHeight) {
          window.setTimeout(function () {
            if (window.HairIDMotion) window.HairIDMotion.scrollTo(result);
          }, 120);
        }
      });
    });
  }

